def control(cfg, action):
    return CONTROL[style(cfg)][("create", "pause", "resume", "cancel").index(action)]


def style(cfg):
    value = cfg.get("profile", {}).get("personality", "friendly")
    return value if value in BANK else "friendly"


def phrase(cfg, event, variant=0):
    rows = BANK[style(cfg)][event]
    return rows[variant % len(rows)]


def invitation(cfg, party, variant=0):
    owner = cfg.get("owner_name") or "Владелец Крест"
    when = datetime.fromtimestamp(party["starts"]).strftime("%d.%m в %H:%M")
    lead = phrase(cfg, "intro", variant)
    facts = f"{owner}: {party['game']}, {when} по времени его компьютера. Состав: {party['size']} с владельцем."
    return (
        lead
        + " "
        + facts
        + " Ответь «готов», «через 20 минут» или «пас». Можно задать вопрос о сборе."
    )


def ready_text(cfg, variant=0):
    return phrase(cfg, "ready", variant)


def message(cfg, event, variant=0, *, reason="", after_game=False):
    lead = phrase(cfg, event, variant)
    if event in {"check", "clarify"}:
        body = " Ответь «готов», «через 20 минут» или «пас»."
    elif event == "reserve":
        body = " Запускать игру пока не нужно."
    elif event == "ack":
        body = " Передам после игры." if after_game else " Передам владельцу."
    else:
        body = ""
    return "Крест: " + (reason + " " if reason else "") + lead + body


def question_answer(party, members, cfg=None, variant=0):
    cfg = cfg or {}
    when = datetime.fromtimestamp(party["starts"]).strftime("%d.%m %H:%M")
    names = (
        ", ".join(
            m["name"] for m in members if m["state"] in {"ready", "joined", "delayed", "waiting"}
        )
        or "состав уточняется"
    )
    return (
        phrase(cfg, "intro", variant)
        + f" {party['game']}, {when} по времени компьютера владельца. "
        f"Состав: {party['size']} с владельцем. Участники: {names}. "
        + phrase(cfg, "check", variant)
        + " Ответь «готов», время или «пас»."
    )


def summary(cfg, party):
    if not party:
        return "Сбора пока нет" if style(cfg) == "concise" else "Сбора компании пока нет"
    members = party["members"]
    ready = [m["name"] for m in members if m["state"] == "ready"]
    waiting = [
        m["name"]
        for m in members
        if m["state"] in {"delayed", "waiting", "joined", "invited", "queued"}
    ]
    uncertain = sum(m["state"] in {"unknown", "uncertain"} for m in members)
    reserve = sum(m["state"] == "reserve" for m in members)
    prefix = {
        "paused": "Сбор на паузе. ",
        "cancelled": "Сбор отменён. ",
        "expired": "Время сбора истекло. ",
        "started": "Запуск передан Steam. ",
    }.get(party["status"], "")
    base = f"{party['game']}: готовы {len(ready)} из {party['size'] - 1} друзей."
    times = [m for m in members if m["state"] == "delayed" and m.get("due")]
    nearest = min(times, key=lambda m: m["due"]) if times else None
    eta = (
        f" Ближайшее время: {nearest['name']}, {datetime.fromtimestamp(nearest['due']):%H:%M}; готовность ещё нужно подтвердить."
        if nearest
        else ""
    )
    current = style(cfg)
    if current == "concise":
        return (
            prefix
            + base
            + (f" Ждём {len(waiting)}." if waiting else "")
            + (f" Не определились: {uncertain}." if uncertain else "")
        )
    if current == "tactical":
        return (
            prefix
            + base
            + f" Ожидают: {len(waiting)}. Не определились: {uncertain}. Резерв: {reserve}."
            + eta
        )
    details = (" Готовы: " + ", ".join(ready) + "." if ready else "") + (
        " Ожидаю: " + ", ".join(waiting) + "." if waiting else ""
    )
    if current == "calm":
        return prefix + base + eta + (details if not eta else "")
    if current == "lively":
        occupied = sum(
            m["state"] not in {"reserve", "declined", "no_response", "send_failed"} for m in members
        )
        return prefix + base + f" Свободных мест: {max(0, party['size'] - 1 - occupied)}." + details
    if current == "ironic":
        return (
            prefix
            + base
            + details
            + (" Организационный рейд ещё идёт." if party["status"] == "collecting" else "")
        )
    if current == "gothic":
        details = details.replace("Готовы:", "Готовые спутники:")
    return prefix + base + details


