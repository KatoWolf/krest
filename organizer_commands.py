def parse_create(text):
    s = normalize(text)
    s = re.sub(r"^(?:собери (?:нас|компанию|друзей|пати)|созови друзей)\s*", "", s)
    values = {}
    count = re.search(
        r"(?:начинаем\s+)?(?:когда (?:нас )?(?:будет )?|на\s+)("
        + "|".join(COUNTS)
        + r"|10|[2-9])(?:\s+человек)?\b",
        s,
    )
    if count:
        word = count[1]
        values["size"] = int(word) if word.isdigit() else COUNTS[word]
        s = s[: count.start()] + s[count.end() :]
    when = re.search(
        rf"\b(?:сегодня вечером|вечером|сейчас|через (?:полчаса|час|{NUM_PATTERN}\s+(?:минут\w*|час\w*))|(?:завтра )?в\s+\d{{1,2}}(?::\d{{2}})?)\b",
        s,
    )
    if when:
        values["when"] = when[0]
        s = s[: when.start()] + s[when.end() :]
    s = re.sub(r"\s+", " ", s).strip()
    s = re.sub(r"^(?:в|играть в)\s+", "", s).strip()
    if s:
        values["game"] = s
    return values
