def action_reply(skill_id, text, state):
    """Do not hide errors, idempotent 'already' results or extra provider details."""
    if skill_id not in TRANSPORT_TEXT and skill_id not in ACKNOWLEDGE:
        return text
    if "уже" in text.casefold():
        return text
    style = (
        getattr(state, "config_getter", lambda: {})()
        .get("profile", {})
        .get("personality", "friendly")
    )
    style = style if style in NEXT else "friendly"
    expected, bank = TRANSPORT_TEXT.get(skill_id, (None, DONE))
    if expected is not None and text != expected:
        return text
    key = (style, skill_id)
    if not hasattr(state, "_action_reply_decks"):
        state._action_reply_decks, state._last_action_reply = {}, {}
    deck = state._action_reply_decks.get(key)
    if not deck:
        deck = list(bank[style])
        random.shuffle(deck)
        if len(deck) > 1 and deck[-1] == state._last_action_reply.get(key):
            deck[0], deck[-1] = deck[-1], deck[0]
        state._action_reply_decks[key] = deck
    phrase = deck.pop()
    state._last_action_reply[key] = phrase
    if style == "concise" and expected is None:
        return text  # The result already says what happened; no redundant «Готово».
    return phrase if expected else phrase + " " + text
