"""Connect an existing bot folder through a separate, reviewable launcher."""

import ast
import json
from pathlib import Path

GENERATED = {"krest_bridge_launcher.py", "krest_bridge_adapter.py"}


def entrypoints(folder):
    root = Path(folder).resolve(strict=True)
    preferred = ("main.py", "bot.py", "krest_bot.py", "run.py", "ds_session.py")
    scripts = [p for p in root.glob("*.py") if p.name not in GENERATED and p.name != "__init__.py"]
    return sorted(
        scripts, key=lambda p: (preferred.index(p.name) if p.name in preferred else 99, p.name)
    )


def connect_project(entrypoint):
    script = Path(entrypoint).resolve(strict=True)
    if script.suffix.lower() != ".py" or script.name in GENERATED:
        raise ValueError("Выберите исходный запускаемый .py файл бота")
    ast.parse(script.read_text(encoding="utf-8-sig"))
    root = script.parent
    launcher = root / "krest_bridge_launcher.py"
    adapter = root / "krest_bridge_adapter.py"
    manifest = launcher.with_suffix(".krest.json")
    marker = "# Generated by Krest bot connector v1\n"
    for target in (launcher, adapter):
        if target.exists() and not target.read_text(encoding="utf-8").startswith(marker):
            raise ValueError("Файл уже существует и не создан Крест: " + target.name)
    if manifest.exists():
        try:
            owned = (
                json.loads(manifest.read_text(encoding="utf-8")).get("generated_by")
                == "krest_bot_connector_v1"
            )
        except (ValueError, AttributeError):
            owned = False
        if not owned:
            raise ValueError("Файл уже существует и не создан Крест: " + manifest.name)
    from storage import atomic_write_text

    adapter_source = Path(__file__).with_name("bot_bridge_adapter.py").read_text(encoding="utf-8")
    atomic_write_text(adapter, marker + adapter_source)
    atomic_write_text(
        launcher,
        marker + "import os, runpy, sys\nfrom pathlib import Path\n"
        "root = Path(__file__).resolve().parent\nos.chdir(root)\nsys.path.insert(0, str(root))\n"
        "from krest_bridge_adapter import install\ninstall()\n"
        + f"sys.argv = [str(root / {script.name!r})]\nrunpy.run_path(sys.argv[0], run_name='__main__')\n",
    )
    atomic_write_text(
        manifest,
        json.dumps(
            {
                "api_version": 1,
                "generated_by": "krest_bot_connector_v1",
                "entrypoint": script.name,
                "name": root.name[:80],
                "permissions": ["notifications", "refresh", "discord_control"],
            },
            ensure_ascii=False,
            indent=2,
        ),
    )
    return str(launcher)
